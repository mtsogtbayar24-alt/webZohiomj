<?php
/**
 * Бодлого 116 (д): Нийлбэрийг олох
 * Илэрхийлэл: Σ (k / (k + 1) - cos^k(|x|))
 */

// 1. Утгуудыг тохируулах (Жишээ утга авлаа)
$n = 10; // n натурал тоо
$x = 1.5; // x бодит тоо

// 2. Шаардлагатай хувьсагчдыг зарлах
$total_sum = 0;

// 3. Илэрхийллийг бодож, үр дүнг хэвлэх
for ($k = 1; $k <= $n; $k++) {
    // k / (k + 1) хэсэг
    $term1 = $k / ($k + 1);
    
    // cos^k(|x|) хэсэг
    $abs_x = abs($x);
    $cos_x = cos($abs_x);
    $term2 = pow($cos_x, $k);
    
    // Нийлбэрт нэмэх
    $total_sum += ($term1 - $term2);
}

// Үр дүнг форматлаж харуулах
echo "Өгөгдсөн утгууд: n = $n, x = $x\n";
echo "Нийлбэрийн утга: " . number_format($total_sum, 4) . "\n";
?>